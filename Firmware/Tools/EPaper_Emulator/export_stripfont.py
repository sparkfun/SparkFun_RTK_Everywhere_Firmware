######################################################################################
#
# export_stripfont.py
#
# Writes ../../RTK_Everywhere/fontStripText.h: Terminus Bold capitals, digits, '-' and space
# for the 184x88 top status strip (fix state word, Bluetooth ID), as displayBitmap() bitmaps
# (column-major, bit 0 = top row, 8-row bands). Each glyph is cropped to the cap height (no
# descenders - capitals and digits only; Q's tail adds two rows) and keeps the font's full advance width, so the
# font's own 1 px letter spacing is built in. See printStripText() in Display.ino.
#
# Use: python export_stripfont.py
#
######################################################################################

from pathlib import Path

FONT_DIR = Path(__file__).parent / "assets" / "fonts"
OUT_H = Path(__file__).parent.parent.parent / "RTK_Everywhere" / "fontStripText.h"
CHARS = " -0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
FONTS = (("stripText20", "ter-u20b.bdf"),)


def read_bdf(filename):
    """Return (advance width, cap height, {char: rows of bools}) cropped to the cap box."""
    lines = (FONT_DIR / filename).read_text(encoding="latin-1").splitlines()
    ascent = next(int(l.split()[1]) for l in lines if l.startswith("FONT_ASCENT"))
    descent = next(int(l.split()[1]) for l in lines if l.startswith("FONT_DESCENT"))
    wanted = {ord(ch): ch for ch in CHARS}
    glyphs, advance = {}, 0
    i = 0
    while i < len(lines):
        if lines[i].startswith("ENCODING") and int(lines[i].split()[1]) in wanted:
            ch = wanted[int(lines[i].split()[1])]
            while not lines[i].startswith("DWIDTH"):
                i += 1
            advance = int(lines[i].split()[1])
            while not lines[i].startswith("BBX"):
                i += 1
            w, h, xoff, yoff = map(int, lines[i].split()[1:5])
            while lines[i] != "BITMAP":
                i += 1
            grid = [[False] * advance for _ in range(ascent + descent)]
            top = ascent - (yoff + h)
            for r, hexrow in enumerate(lines[i + 1 : i + 1 + h]):
                bits = bin(int(hexrow, 16))[2:].zfill(len(hexrow) * 4)
                for c in range(w):
                    if bits[c] == "1" and 0 <= xoff + c < advance:
                        grid[top + r][xoff + c] = True
            glyphs[ch] = grid
        i += 1

    # Cap box: the rows inked by any capital or digit
    inked = [r for ch in CHARS.strip(" -") for r, row in enumerate(glyphs[ch]) if any(row)]
    first, last = min(inked), max(inked)
    glyphs = {ch: grid[first : last + 1] for ch, grid in glyphs.items()}
    return advance, last - first + 1, glyphs


def bitmap_bytes(grid, width):
    height = len(grid)
    data = []
    for band in range((height + 7) // 8):
        for col in range(width):
            byte = 0
            for bit in range(8):
                row = band * 8 + bit
                if row < height and grid[row][col]:
                    byte |= 1 << bit
            data.append(byte)
    return data


def c_name(ch):
    return {" ": "space", "-": "dash"}.get(ch, ch)


def main():
    out = ["// Generated by Firmware/Tools/EPaper_Emulator/export_stripfont.py - do not edit.",
           "// 184x88 e-paper top strip text: Terminus Font Bold (SIL OFL 1.1, see",
           "// Tools/EPaper_Emulator/assets/fonts/Terminus-OFL.txt) - ter-u20b capitals, digits, '-'",
           "// and space, cropped to the cap height. Uses bigDigitFont_t from",
           "// fontBigDigits.h. See printStripText() in Display.ino.",
           "",
           "#ifndef __FONT_STRIP_TEXT_H__",
           "#define __FONT_STRIP_TEXT_H__",
           ""]
    for name, filename in FONTS:
        advance, height, glyphs = read_bdf(filename)
        for ch in CHARS:
            data = bitmap_bytes(glyphs[ch], advance)
            out.append(f"const uint8_t {name}_{c_name(ch)}[] = {{")
            for start in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02X}" for b in data[start : start + 16]) + ",")
            out.append("};")
        out.append(f"const bigDigitGlyph_t {name}Glyphs[] = {{")
        for ch in CHARS:
            literal = "'\\''" if ch == "'" else f"'{ch}'"
            out.append(f"    {{{literal}, {advance}, {name}_{c_name(ch)}}},")
        out.append("};")
        out.append(f"const bigDigitFont_t {name} = {{{height}, {len(CHARS)}, {name}Glyphs}}; // {filename}, "
                   f"{advance} px advance, {height} px cap height")
        out.append("")
    out.append("#endif // __FONT_STRIP_TEXT_H__")
    OUT_H.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_H}")


if __name__ == "__main__":
    main()
